# Country flags are a pair of "regional indicator" letters. Windows draws them as the two letters, in which
# case the picker hides them; phones and Macs show the flag.
FLAGS = ("US GB CA AU NZ IE FR DE ES IT PT NL BE CH AT SE NO DK FI IS PL CZ SK HU RO BG GR TR UA RU "
         "MX BR AR CL CO PE VE CU DO PR JM JP KR CN TW HK IN PK BD LK NP TH VN PH ID MY SG "
         "SA AE IL EG ZA NG KE GH MA ET EU UN").split()


def name_of(cp):
    try:
        return unicodedata.name(chr(cp)).lower()
    except ValueError:
        return None   # not assigned in this version of Unicode


def build():
    seen = set()
    groups = []
    for title, points in CATEGORIES:
        rows = []
        for cp in points:
            name = name_of(cp)
            # Skin tone swatches are modifiers, not emoji of their own.
            if cp in seen or name is None or 0x1F3FB <= cp <= 0x1F3FF:
                continue
            seen.add(cp)
            # Characters below U+1F000 mostly default to a plain text drawing; VS16 asks for the emoji one.
            rows.append([chr(cp) + (VS16 if cp < 0x1F000 or name_of(cp) and cp in TEXT_DEFAULT else ""), name])
        groups.append({"name": title, "emoji": rows})
    flags = [["".join(chr(0x1F1E6 + ord(letter) - 65) for letter in code), "flag " + code.lower()] for code in FLAGS]
    groups.append({"name": "Flags", "emoji": flags})
    return groups


